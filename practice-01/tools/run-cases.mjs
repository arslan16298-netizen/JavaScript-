// Прогон таблиц проверок для заданий 3, 4 и расширения.
// Идея: в js/*.js данные задаются строками const ... = ...;
// Скрипт делает временную копию файла с подставленными значениями,
// запускает её через node и сравнивает вывод с ожиданием.
// Запуск из корня репозитория: node practice-01/tools/run-cases.mjs
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tmp = mkdtempSync(path.join(tmpdir(), "pr01-"));

// Запускает файл с подменой констант. Значения передаются как JS-литералы (строки кода).
function run(file, values) {
  let code = readFileSync(path.join(root, "js", file), "utf8");
  for (const [name, literal] of Object.entries(values)) {
    const re = new RegExp(`^const ${name} = .*;$`, "m");
    if (!re.test(code)) throw new Error(`В ${file} нет строки const ${name}`);
    code = code.replace(re, `const ${name} = ${literal};`);
  }
  const copy = path.join(tmp, file);
  writeFileSync(copy, code);
  return execFileSync("node", [copy], { encoding: "utf8" }).trimEnd();
}

let failed = 0;
let total = 0;
function report(title, rows) {
  console.log(`\n=== ${title} ===`);
  for (const row of rows) {
    total += 1;
    const ok = row.test(row.out);
    if (!ok) failed += 1;
    console.log(`${ok ? "OK  " : "FAIL"} | ${row.input} | ${row.expect}`);
    console.log("     " + row.out.split("\n").join("\n     "));
  }
}

